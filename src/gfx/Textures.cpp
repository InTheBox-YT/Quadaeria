static_assert(sizeof(kFiles) / sizeof(kFiles[0]) == T_COUNT, "one file per texture layer");

std::vector<uint32_t> loadTextures(int& layerCount) {
    layerCount = T_COUNT;
    // magenta so missing ones stand out
    std::vector<uint32_t> px(size_t(T_COUNT) * 256, 0xFFFF00FFu);
    for (int t = 0; t < T_COUNT; ++t) {
        std::string path = assetPath(std::string("textures/") + kFiles[t] + ".png");
        int w = 0, h = 0, n = 0;
        unsigned char* data = stbi_load(path.c_str(), &w, &h, &n, 4);
        if (!data || w != TEX_SIZE || h != TEX_SIZE) {
            std::fprintf(stderr, "[quadaeria] missing or bad texture: %s\n", path.c_str());
            if (data) stbi_image_free(data);
            continue;
        }
        for (int i = 0; i < 256; ++i)
            px[size_t(t) * 256 + size_t(i)] =
                uint32_t(data[i * 4]) | uint32_t(data[i * 4 + 1]) << 8 | uint32_t(data[i * 4 + 2]) << 16 | uint32_t(data[i * 4 + 3]) << 24;
        stbi_image_free(data);
    }
    return px;
}

